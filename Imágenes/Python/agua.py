# -*- coding: utf-8 -*-
estado = input("Ingrese el estado del agua: ")
if estado == "sólido":
    print("El agua en estado sólido la encontramos en forma de hielo y nieve en las altas montañas.")
elif estado == "líquido":
    print("El agua en estado líquido es la que bebemos y la encontramos en los ríos, mares, oceanos y lagos.")
else:
    print("El agua en estado gaseoso es la que vemos al esta evaporarse y crear un pequeño humo o gas.")
